$failures = array();

foreach ($cases as $ip => $expected) {
    $actual = $searcher->simple($ip);
    if ($actual !== $expected) {
        $failures[] = sprintf('%s expected `%s`, got `%s`', $ip, $expected, $actual);
    }
}

$method = new ReflectionMethod('Ip2Region', 'getSpecialAddressName');
$method->setAccessible(true);
$negativeCases = array(
    // IPv4 特殊段边界外地址
    '8.8.8.8',
    '100.63.255.255',
    '100.128.0.0',
    '172.15.255.255',
    '172.32.0.0',
    '192.167.255.255',
    '192.169.0.0',

    // IPv6 普通公网示例
    '2001:4860:4860::8888',
    '2400:3200::1',
);

foreach ($negativeCases as $ip) {
    $actual = $method->invoke($searcher, $ip);
    if ($actual !== null) {
        $failures[] = sprintf('%s expected non-special, got `%s`', $ip, $actual);
    }
}

if (!empty($failures)) {
    echo "特殊用途地址测试失败：\n";
    foreach ($failures as $failure) {
        echo "  - {$failure}\n";
    }
    exit(1);
}

